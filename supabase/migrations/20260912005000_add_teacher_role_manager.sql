-- Adds exact-email role management for teachers without exposing an account list.
-- Review against the remote schema before applying. This file has not been pushed.

create table public.role_change_audit (
  id bigint generated by default as identity primary key,
  changed_by uuid references auth.users(id) on delete set null,
  target_user_id uuid references auth.users(id) on delete set null,
  previous_role text not null,
  new_role text not null,
  changed_at timestamptz not null default now()
);

alter table public.role_change_audit enable row level security;

revoke all on table public.role_change_audit from anon, authenticated;

create or replace function public.find_account_by_email(p_email text)
returns table (
  user_id uuid,
  full_name text,
  account_role text
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not exists (
    select 1
    from public.profiles
    where profiles.id = auth.uid()
      and profiles.role = 'teacher'
  ) then
    raise exception using
      errcode = '42501',
      message = 'Only teachers can look up accounts for role management.';
  end if;

  if p_email is null or btrim(p_email) = '' then
    return;
  end if;

  return query
  select profile.id, profile.full_name, profile.role
  from auth.users as auth_user
  inner join public.profiles as profile on profile.id = auth_user.id
  where lower(auth_user.email) = lower(btrim(p_email))
  limit 1;
end;
$$;

create or replace function public.set_account_role(p_user_id uuid, p_role text)
returns table (
  user_id uuid,
  full_name text,
  account_role text
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_role text;
begin
  if not exists (
    select 1
    from public.profiles
    where profiles.id = auth.uid()
      and profiles.role = 'teacher'
  ) then
    raise exception using
      errcode = '42501',
      message = 'Only teachers can manage account roles.';
  end if;

  if p_user_id = auth.uid() then
    raise exception using
      errcode = '42501',
      message = 'Teachers cannot change their own role.';
  end if;

  select profile.role
  into current_role
  from public.profiles as profile
  where profile.id = p_user_id
  for update;

  if not found then
    raise exception using
      errcode = '23503',
      message = 'Account profile does not exist.';
  end if;

  if current_role = 'teacher' then
    raise exception using
      errcode = '42501',
      message = 'Existing teacher accounts cannot be modified.';
  end if;

  if not (
    (current_role = 'parent' and p_role in ('teacher_aide', 'teacher'))
    or (current_role = 'teacher_aide' and p_role in ('parent', 'teacher'))
  ) then
    raise exception using
      errcode = '22023',
      message = 'This role change is not allowed.';
  end if;

  update public.profiles
  set role = p_role
  where id = p_user_id;

  insert into public.role_change_audit (
    changed_by,
    target_user_id,
    previous_role,
    new_role
  ) values (
    auth.uid(),
    p_user_id,
    current_role,
    p_role
  );

  return query
  select profile.id, profile.full_name, profile.role
  from public.profiles as profile
  where profile.id = p_user_id;
end;
$$;

revoke all on function public.find_account_by_email(text) from public, anon;
revoke all on function public.set_account_role(uuid, text) from public, anon;

grant execute on function public.find_account_by_email(text) to authenticated;
grant execute on function public.set_account_role(uuid, text) to authenticated;
